-- Same tables as schema.sql, written for PostgreSQL (used on Render).
-- Dates stay as TEXT 'YYYY-MM-DD' on purpose, so the code works the same on both databases.

CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('owner', 'staff'))
);

CREATE TABLE IF NOT EXISTS suppliers (
    supplier_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT,
    address TEXT
);

CREATE TABLE IF NOT EXISTS products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    brand TEXT,
    category TEXT,
    season TEXT,
    min_stock_level INTEGER DEFAULT 10,
    is_restricted INTEGER DEFAULT 0,
    created_at TEXT DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS batches (
    batch_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products (product_id),
    supplier_id INTEGER REFERENCES suppliers (supplier_id),
    batch_no TEXT NOT NULL,
    quantity_received INTEGER NOT NULL,
    quantity_remaining INTEGER NOT NULL,
    price_per_unit DOUBLE PRECISION NOT NULL,
    purchase_date TEXT NOT NULL,
    expiry_date TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS sales (
    sale_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products (product_id),
    batch_id INTEGER NOT NULL REFERENCES batches (batch_id),
    quantity_sold INTEGER NOT NULL,
    sale_date TEXT DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS'),
    sold_by INTEGER REFERENCES users (user_id),
    buyer_id_proof TEXT
);

CREATE TABLE IF NOT EXISTS restricted_pesticides (
    restricted_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pesticide_name TEXT NOT NULL,
    reason TEXT
);

CREATE INDEX IF NOT EXISTS idx_batches_product ON batches (product_id, expiry_date);
CREATE INDEX IF NOT EXISTS idx_sales_product_date ON sales (product_id, sale_date);
CREATE INDEX IF NOT EXISTS idx_sales_date ON sales (sale_date);
